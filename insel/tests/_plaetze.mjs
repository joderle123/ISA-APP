import { launch } from './lib.mjs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const DIST = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist', 'lycee.html');
const browser = await launch();
const page = await (await browser.newContext({ viewport: { width: 1180, height: 820 } })).newPage();
page.setDefaultTimeout(240000);
const fehler = []; page.on('pageerror', (e) => fehler.push(String(e)));
const ok = (n, c) => console.log((c ? '  ✓ ' : '  ✗ ') + n);
await page.goto('file://' + DIST + '?test');
await page.waitForSelector('.ly-t-plaetze');
ok('Drei Plätze auf dem Titelbild', (await page.$$('.ly-t-plaetze button')).length === 3);
await page.click('[data-a="neu"]'); await page.fill('.ly-w-name input', 'Eins'); await page.click('[data-a="start"]');
await page.waitForFunction(() => window.LYCEE && LYCEE.zustand && LYCEE.zustand.name === 'Eins');
await page.waitForTimeout(1500);
await page.reload(); await page.waitForSelector('.ly-t-plaetze');
ok('Platz 1 zeigt Eins', /Eins/.test(await page.textContent('.ly-t-plaetze [data-p="1"]')));
await page.click('.ly-t-plaetze [data-p="2"]');
ok('Platz 2 ist frei (kein Weiterspielen)', !(await page.$('[data-a="weiter"]')));
await page.click('[data-a="neu"]'); await page.fill('.ly-w-name input', 'Zwei'); await page.click('[data-a="start"]');
await page.waitForFunction(() => window.LYCEE && LYCEE.zustand && LYCEE.zustand.name === 'Zwei');
await page.waitForTimeout(1500);
ok('Platz 1 bleibt erhalten', JSON.parse(await page.evaluate(() => localStorage.getItem('lycee.stand'))).name === 'Eins');
ok('Platz 2 gespeichert', JSON.parse(await page.evaluate(() => localStorage.getItem('lycee.stand.2'))).name === 'Zwei');
await page.reload(); await page.waitForSelector('.ly-t-plaetze');
ok('Nach Neuladen ist Platz 2 gewählt', await page.evaluate(() => document.querySelector('.ly-t-plaetze [data-p="2"]').classList.contains('an')));
ok('Keine Fehler', fehler.length === 0);
await browser.close();
